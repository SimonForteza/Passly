-- Referencia del esquema JPA PAS-31. Ejecutar CREATE SCHEMA en volumenes existentes.
CREATE SCHEMA IF NOT EXISTS accesos;
CREATE TABLE IF NOT EXISTS accesos.validacion (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id bigint,
 evento_id bigint NOT NULL,
 validador_id bigint NOT NULL,
 resultado varchar(20) NOT NULL,
 momento timestamptz NOT NULL
);
ALTER TABLE tickets.ticket ADD COLUMN IF NOT EXISTS usado_en timestamptz;
